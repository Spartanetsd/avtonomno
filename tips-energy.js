// «див. пораду [[id]]» → номер поради. Невідомий id лишається як є — його ловить тест.
const NUM = new Map(TIPS_ENERGY.map((t, i) => [t.id, i + 1]));
/** @param {string} s */
const fill = (s) => s.replace(/\[\[([^\]]+)\]\]/g, (m, id) => String(NUM.get(id) || m));
for (const t of TIPS_ENERGY) {
  t.t = fill(t.t);
  if (t.d) t.d = fill(t.d);
  if (t.why) t.why = fill(t.why);
  if (t.how) t.how = t.how.map(fill);
  if (t.warn) t.warn = t.warn.map(fill);
}
